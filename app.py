
import io
import os
import tempfile
from pathlib import Path
from contextlib import redirect_stdout

from flask import Flask, render_template, request
from werkzeug.utils import secure_filename

from main import analyze_file


MAX_UPLOAD_BYTES = 5 * 1024 * 1024
ALLOWED_EXTENSIONS = {".yaml", ".yml", ".json"}

app = Flask(__name__)
app.config["MAX_CONTENT_LENGTH"] = MAX_UPLOAD_BYTES + (1024 * 1024)


def parse_report(report):
    """
    Convert the ASCII table generated by main.py
    into structured data for the HTML template.
    """

    headers = []
    rows = []
    messages = []

    for raw_line in report.splitlines():
        line = raw_line.strip()

        if not line:
            continue

        if line.startswith("--- Kubernetes Resource Summary ---"):
            continue

        # Ignore ASCII table borders
        if line.startswith("+") and set(line) <= set("+-=+"):
            continue

        # Extract table rows
        if line.startswith("|") and "|" in line:
            cells = [
                cell.strip()
                for cell in line.strip("|").split("|")
            ]

            if not headers:
                headers = cells
            else:
                rows.append(cells)

        else:
            messages.append(line)

    # Make every row consistent with the header count
    if headers:
        normalized_rows = []

        for row in rows:
            if len(row) < len(headers):
                row.extend(["—"] * (len(headers) - len(row)))

            normalized_rows.append(row[:len(headers)])

        rows = normalized_rows

    return headers, rows, messages


@app.route("/healthz")
def health():
    return {"status": "ok"}


@app.route("/", methods=["GET"])
def home():
    return render_template("index.html")


@app.route("/analyze", methods=["POST"])
def analyze():

    uploaded_file = request.files.get("file")

    if not uploaded_file or not uploaded_file.filename:
        return render_template(
            "index.html",
            error="Please select a file to analyze."
        ), 400

    filename = secure_filename(uploaded_file.filename)
    extension = Path(filename).suffix.lower()

    if extension not in ALLOWED_EXTENSIONS:
        return render_template(
            "index.html",
            error="Only YAML, YML, and JSON files are supported."
        ), 400

    contents = uploaded_file.stream.read(MAX_UPLOAD_BYTES + 1)

    if not contents:
        return render_template(
            "index.html",
            error="The uploaded file is empty."
        ), 400

    if len(contents) > MAX_UPLOAD_BYTES:
        return render_template(
            "index.html",
            error="File size exceeds the 5 MB limit."
        ), 413

    temporary_path = None

    try:

        with tempfile.NamedTemporaryFile(
            mode="wb",
            suffix=extension,
            delete=False
        ) as temporary_file:

            temporary_file.write(contents)
            temporary_path = temporary_file.name

        output = io.StringIO()

        with redirect_stdout(output):
            analyze_file(temporary_path)

        headers, rows, messages = parse_report(
            output.getvalue()
        )

        return render_template(
            "index.html",
            filename=filename,
            headers=headers,
            rows=rows,
            messages=messages
        )

    except Exception:

        app.logger.exception("Manifest analysis failed.")

        return render_template(
            "index.html",
            error="Unable to analyze the uploaded file."
        ), 500

    finally:

        if temporary_path and os.path.exists(temporary_path):
            os.remove(temporary_path)


@app.errorhandler(413)
def file_too_large(error):

    return render_template(
        "index.html",
        error="Upload exceeds the allowed request size."
    ), 413


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=5000, debug=False)